package kz.dentvision.crm.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Шкала отступов, кратная 4. Веб живёт на шкале Tailwind (`p-1`=4px,
 * `p-2`=8px, `p-3`=12px, `p-4`=16px, `p-6`=24px, `p-8`=32px) — это она же.
 *
 * Произвольные значения (11.dp, 14.dp, 22.dp) в экранах запрещены: из-за них
 * одинаковые по смыслу карточки на разных экранах выглядят по-разному, и
 * расхождение накапливается незаметно, потому что каждое в отдельности
 * выглядит правдоподобно.
 */
object DvSpacing {
    /** 4.dp — зазор между строкой и её подписью. */
    val xs = 4.dp

    /** 8.dp — расстояние внутри одного смыслового блока. */
    val sm = 8.dp

    /** 12.dp — расстояние между карточками в списке. */
    val md = 12.dp

    /** 16.dp — внутренний отступ карточки, расстояние между блоками. */
    val lg = 16.dp

    /** 20.dp — крупный внутренний отступ (шапки, герои). */
    val xl = 20.dp

    /** 24.dp — отбивка секции от следующей. */
    val xxl = 24.dp

    /** 32.dp — поля пустого состояния и полноэкранных заглушек. */
    val xxxl = 32.dp
}
