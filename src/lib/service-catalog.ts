export const ALL_SERVICES: Service[] = Object.entries(CATALOG).flatMap(
  ([cat, rows]) =>
    rows.map(([id, name, price, durationMin, matCost, icd]) => ({
      id,
      cat,
      name,
      price,
      durationMin,
      matCost,
      ...(icd ? { icd } : {}),
    })),
)

/** Категории в порядке каталога — годится и как фильтр, и как порядок вывода. */
export const SERVICE_CATEGORIES: string[] = Object.keys(CATALOG)

const BY_ID = new Map(ALL_SERVICES.map((s) => [s.id, s]))

export function findService(id: string | null | undefined): Service | undefined {
  return id ? BY_ID.get(id) : undefined
}

/**
 * Услуги, которыми обычно лечат этот диагноз.
 *
 * Сравнение по корню кода (`K02.1` → `K02`) намеренно: врач ставит диагноз с
 * той точностью, с какой хочет, и правило, привязанное к `K02.1`, не должно
 * молчать на приёме, закрытом с `K02.9`.
 */
export function servicesForDiagnosis(code: string | null | undefined): Service[] {
  const raw = String(code || '').trim().toUpperCase()
  if (!raw) return []
  const root = raw.split('.')[0]
  return ALL_SERVICES.filter((s) =>
    (s.icd || []).some((c) => c === raw || c.split('.')[0] === root),
  )
}
